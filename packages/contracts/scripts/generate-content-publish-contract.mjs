import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('content-publish.contract.json', root), 'utf8'))
const tsTarget = new URL('src/content-publish.generated.ts', root)
const exTarget = new URL(
  '../../backend/api/lib/groupher_server/cms/content_publish_contract.ex',
  root,
)

const entries = Object.entries(source.errorCodes)
const tsCodes = entries.map(([name, code]) => `  ${name}: ${code},`).join('\n')
const ts = `// Generated by scripts/generate-content-publish-contract.mjs. Do not edit directly.\nexport const CONTENT_PUBLISH_ERROR_CODE = {\n${tsCodes}\n} as const\n\nexport type TContentPublishErrorCode =\n  (typeof CONTENT_PUBLISH_ERROR_CODE)[keyof typeof CONTENT_PUBLISH_ERROR_CODE]\n`

const errorLines = entries
  .map(([name, code]) => {
    const reason = name.toLowerCase()
    return `      error(:${reason}, code: ${code}, actions: [:reconcile])`
  })
  .join('\n')
const ex = `# Generated by packages/contracts/scripts/generate-content-publish-contract.mjs. Do not edit directly.\ndefmodule GroupherServer.CMS.ContentPublishContract do\n  @moduledoc \"\"\"\n  Registers generated Content Publisher error codes at the CMS ErrorCat boundary.\n\n      content-publish.contract.json -> generated registration macro -> CMS.ErrorCat\n  \"\"\"\n\n  @doc \"Injects the generated Publisher conflict errors into the calling ErrorCat module.\"\n  defmacro define_errors do\n    quote do\n${errorLines}\n    end\n  end\nend\n`

const outputs = [
  [tsTarget, ts],
  [exTarget, ex],
]

if (process.argv.includes('--check')) {
  const mismatches = []
  for (const [target, expected] of outputs) {
    const actual = await readFile(target, 'utf8').catch(() => '')
    if (actual !== expected) mismatches.push(fileURLToPath(target))
  }
  if (mismatches.length) {
    console.error(`Generated content publish contract is stale:\n${mismatches.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
}
