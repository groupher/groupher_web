import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('auth.contract.json', root), 'utf8'))
const tsTarget = new URL('src/auth.generated.ts', root)
const exTarget = new URL('../../backend/api/lib/groupher_server/auth/contract.ex', root)

const tsCodes = source.errorCodes.map((code) => `  ${code}: '${code}',`).join('\n')
const ts = `// Generated by scripts/generate-auth-contract.mjs. Do not edit directly.\nexport const AUTH_ERROR = {\n${tsCodes}\n} as const\n\nexport type TAuthErrorCode = (typeof AUTH_ERROR)[keyof typeof AUTH_ERROR]\n\nexport const PHOENIX_BROWSER_TOKEN_CLAIMS = {\n  issuer: '${source.phoenixBrowserTokenClaims.issuer}',\n  audience: '${source.phoenixBrowserTokenClaims.audience}',\n  type: '${source.phoenixBrowserTokenClaims.type}',\n} as const\n`

const exCodes = source.errorCodes.map((code) => `    ${code.toLowerCase()}: "${code}"`).join(',\n')
const claims = source.phoenixBrowserTokenClaims
const ex = `# Generated by packages/contracts/scripts/generate-auth-contract.mjs. Do not edit directly.\ndefmodule GroupherServer.Auth.Contract do\n  @moduledoc \"Phoenix mirror of the generated public auth protocol contract.\"\n\n  @codes %{\n${exCodes}\n  }\n\n  @phoenix_browser_token_claims %{\n    issuer: "${claims.issuer}",\n    audience: "${claims.audience}",\n    type: "${claims.type}"\n  }\n\n  @spec all() :: %{atom() => String.t()}\n  def all, do: @codes\n\n  for {name, _value} <- @codes do\n    @spec unquote(name)() :: String.t()\n    def unquote(name)(), do: @codes[unquote(name)]\n  end\n\n  @spec phoenix_browser_token_claims() :: %{atom() => String.t()}\n  def phoenix_browser_token_claims, do: @phoenix_browser_token_claims\n\n  @spec phoenix_token_issuer() :: String.t()\n  def phoenix_token_issuer, do: @phoenix_browser_token_claims.issuer\n\n  @spec phoenix_token_audience() :: String.t()\n  def phoenix_token_audience, do: @phoenix_browser_token_claims.audience\n\n  @spec phoenix_token_type() :: String.t()\n  def phoenix_token_type, do: @phoenix_browser_token_claims.type\nend\n`

const generatedEx = ex.replace(
  '  @moduledoc "Phoenix mirror of the generated public auth protocol contract."',
  `  @moduledoc """
  Phoenix mirror of the generated public auth protocol contract.

  Auth request
    -> generated contract values
    -> Phoenix and Assets Hub verification
  """`,
)

const outputs = [
  [tsTarget, ts],
  [exTarget, generatedEx],
]
if (process.argv.includes('--check')) {
  const mismatches = []
  for (const [target, expected] of outputs) {
    const actual = await readFile(target, 'utf8').catch(() => '')
    if (actual !== expected) mismatches.push(fileURLToPath(target))
  }
  if (mismatches.length) {
    console.error(`Generated auth contract is stale:\n${mismatches.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
}
